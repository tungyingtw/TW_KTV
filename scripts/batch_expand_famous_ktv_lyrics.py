def batch_expand():
    catalog_path = "public/songs_catalog.json"
    if not os.path.exists(catalog_path):
        print("找不到 public/songs_catalog.json")
        return

    with open(catalog_path, "r", encoding="utf-8") as f:
        catalog = json.load(f)

    updated = 0
    for song in catalog:
        artist = song.get("artist", "").strip()
        title = song.get("title", "").strip()
        
        # 精準匹配
        key = (artist, title)
        if key in FAMOUS_HITS_LYRICS:
            song["lyricsSnippet"] = FAMOUS_HITS_LYRICS[key]
            updated += 1
            continue

        # 模糊匹配
        for (a, t), lyric in FAMOUS_HITS_LYRICS.items():
            if t == title and (a in artist or artist in a):
                song["lyricsSnippet"] = lyric
                updated += 1
                break

    with open(catalog_path, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    print(f"🎉 成功為全台 KTV 巨星經典熱門歌庫注入歌詞，共升級 {updated} 首！")

if __name__ == "__main__":
    batch_expand()
